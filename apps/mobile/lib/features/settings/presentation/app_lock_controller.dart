import 'dart:async';
import 'package:flutter/widgets.dart';
import '../domain/device_owner_auth.dart';
import '../../../l10n/l10n.dart';

class AppLockController extends ChangeNotifier {
  AppLockController(this.auth, {DateTime Function()? now})
    : _now = now ?? DateTime.now;
  final DeviceOwnerAuth auth;
  final DateTime Function() _now;
  bool ready = false, shielded = true, requiresUnlock = false;
  bool _enabled = true, _protected = false, _active = true, _disposed = false;
  bool _authenticating = false;
  bool get authenticating => _authenticating;

  /// Whether the cover is drawn. [shielded] also holds while the app is merely
  /// inactive so work waits for the foreground, but the app stays visible in
  /// the switcher; only startup and a required unlock hide it.
  bool get covered => !ready || requiresUnlock;
  String? error;
  DateTime? _backgroundedAt;
  int _generation = 0;

  void initialize({required bool enabled, required bool hasProtectedContent}) {
    if (ready) return;
    _enabled = enabled;
    _protected = hasProtectedContent;
    ready = true;
    requiresUnlock = enabled && hasProtectedContent;
    shielded = !_active || requiresUnlock;
    _notify();
  }

  void setEnabled(bool value) {
    if (_enabled == value) return;
    _enabled = value;
    if (!value) _clear();
    _notify();
  }

  void setProtectedContent(bool value) {
    if (_protected == value) return;
    _protected = value;
    if (!value && ready) _clear();
    _notify();
  }

  void lock() {
    _invalidate();
    if (_enabled && _protected) requiresUnlock = true;
    shielded = true;
    _notify();
  }

  // Only hidden/paused record a real background. Inactive is also generated by
  // the system authentication sheet, so it shields without cancelling that prompt.
  bool lifecycle(AppLifecycleState state) {
    if (state == AppLifecycleState.resumed) {
      _active = true;
      if (!ready) return false;
      final hadBackground = _backgroundedAt != null;
      if (!_enabled || !_protected) {
        _clear();
      } else {
        final backgroundedAt = _backgroundedAt;
        _backgroundedAt = null;
        if (backgroundedAt != null &&
            _now().difference(backgroundedAt) >= const Duration(seconds: 300)) {
          requiresUnlock = true;
        }
        shielded = requiresUnlock;
      }
      _notify();
      return hadBackground && requiresUnlock && !authenticating;
    }
    _active = false;
    shielded = true;
    if (state == AppLifecycleState.hidden ||
        state == AppLifecycleState.paused ||
        state == AppLifecycleState.detached) {
      if (_backgroundedAt == null) {
        _backgroundedAt = _now();
        _invalidate();
      }
    }
    _notify();
    return false;
  }

  Future<void> authenticate() async {
    if (!ready || !requiresUnlock || authenticating || !_active || _disposed) {
      return;
    }
    _authenticating = true;
    error = null;
    final generation = _generation;
    _notify();
    try {
      final supported = await auth.isSupported();
      if (_disposed || generation != _generation) return;
      if (!supported) {
        error = appStrings.settingsLockSetup;
      } else {
        final success = await auth.authenticate();
        if (_disposed || generation != _generation) return;
        if (success) {
          requiresUnlock = false;
          shielded = !_active;
          error = null;
        } else {
          error = appStrings.settingsLockStillLocked;
        }
      }
    } catch (_) {
      if (!_disposed && generation == _generation) {
        error = appStrings.settingsLockCancelled;
      }
    } finally {
      if (!_disposed) {
        _authenticating = false;
        _notify();
      }
    }
  }

  void _invalidate() {
    _generation++;
    if (authenticating) unawaited(auth.stop().catchError((Object _) {}));
  }

  void _clear() {
    _invalidate();
    _backgroundedAt = null;
    requiresUnlock = false;
    shielded = !ready || !_active;
    error = null;
  }

  void _notify() {
    if (!_disposed) notifyListeners();
  }

  @override
  void dispose() {
    _invalidate();
    _disposed = true;
    super.dispose();
  }
}
